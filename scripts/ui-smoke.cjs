const { launch } = require('./launch.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { fixtures } = require('./fixtures.cjs');

async function main() {
  const root = path.resolve(__dirname, '..');
  const photos = path.join(root, 'artifacts', 'ui-photos');
  const data = await fs.mkdtemp(path.join(os.tmpdir(), 'photocull-ui-'));
  const screenshots = path.join(root, 'artifacts');
  await fs.rm(photos, { recursive: true, force: true });
  await fixtures(photos, 36);
  const raw = path.join(root, 'artifacts', 'fixtures', 'iss030e122639.NEF');
  try { await fs.copyFile(raw, path.join(photos, '000_NASA.NEF')); } catch { /* A RAW fixture is optional for this UI test. */ }
  let app;
  const errors = [];
  try {
    app = await launch({ env: { ...process.env, PHOTOCULL_DATA_DIR: data } });
    app.process().stderr.on('data', chunk => { if (process.env.DEBUG_UI) process.stderr.write(chunk); });
    const page = await app.firstWindow();
    page.on('pageerror', e => errors.push(e.message));
    await page.locator('#empty-open').waitFor();
    await page.screenshot({ path: path.join(screenshots, 'photocull-empty.png') });
    await page.evaluate(folder => window.loadTestFolder(folder), photos);
    await page.waitForFunction(() => document.querySelector('#review-image').dataset.complete === 'yes', { timeout: 60000 });
    assert.ok(Number(await page.locator('#count-all').textContent()) >= 36);
    await page.keyboard.press('5');
    await page.keyboard.press('p');
    await page.waitForFunction(() => document.querySelector('#count-pick').textContent === '1');
    assert.equal(await page.locator('#count-rated').textContent(), '1');
    await page.keyboard.press('Control+z');
    await page.waitForFunction(() => document.querySelector('#count-pick').textContent === '0');
    await page.keyboard.press('Control+Shift+z');
    await page.waitForFunction(() => document.querySelector('#count-pick').textContent === '1');
    await page.keyboard.press('ArrowRight');
    await page.keyboard.press('x');
    await page.waitForFunction(() => document.querySelector('#count-reject').textContent === '1');
    await page.keyboard.press('Space');
    await page.waitForFunction(() => document.querySelector('#image-viewport').classList.contains('zoomed'));
    await page.keyboard.press('Space');
    await page.waitForFunction(() => !document.querySelector('#image-viewport').classList.contains('zoomed'));
    await page.keyboard.press('g');
    await page.locator('.grid-card').first().waitFor();
    const cardCount = await page.locator('.grid-card').count();
    assert.ok(cardCount < Number(await page.locator('#count-all').textContent()), 'Grid must virtualize its image elements');
    await page.screenshot({ path: path.join(screenshots, 'photocull-grid.png') });
    const cards = page.locator('.grid-card'), picksBefore = Number(await page.locator('#count-pick').textContent());
    await cards.nth(4).click(); await cards.nth(7).click({ modifiers: ['Shift'] });
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 4);
    assert.match(await page.locator('#view-count').textContent(), /· 4 selected/);
    assert.equal(await page.locator('#detail-decision').textContent(), '4 photos selected');
    const focused = await page.locator('#photo-name').textContent();
    await page.keyboard.press('p');
    await page.waitForFunction(n => Number(document.querySelector('#count-pick').textContent) === n, picksBefore + 4);
    assert.equal(await page.locator('#photo-name').textContent(), focused, 'batch decisions do not auto-advance');
    await page.keyboard.press('Control+z');
    await page.waitForFunction(n => Number(document.querySelector('#count-pick').textContent) === n, picksBefore);
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 4);
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 1);
    await cards.nth(4).click(); await page.keyboard.press('Shift+ArrowRight');
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 2);
    await page.keyboard.press('Shift+ArrowLeft');
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 1);
    await cards.nth(6).click({ modifiers: ['Control'] });
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 2);
    await cards.nth(6).click({ modifiers: ['Control'] });
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 1);
    const current = page.locator('.grid-card.current'), currentName = await current.getAttribute('aria-label');
    await current.click({ modifiers: ['Control'] });
    await page.waitForFunction(() => document.querySelectorAll('.grid-card.selected').length === 0);
    assert.equal(await page.locator('#photo-name').textContent(), currentName, 'unmarking the last photo preserves review focus');
    await page.keyboard.press('Control+a');
    assert.match(await page.locator('#view-count').textContent(), new RegExp(`· ${await page.locator('#count-all').textContent()} selected`));
    await page.keyboard.press('Escape');
    const first = await cards.first().boundingBox();
    const secondRow = await cards.evaluateAll(nodes => {
      const first = nodes[0].getBoundingClientRect();
      const next = nodes.find(node => node.getBoundingClientRect().top > first.top + first.height);
      const box = next.getBoundingClientRect(); return { x: box.x, y: box.y, width: box.width, height: box.height };
    });
    await page.mouse.move(first.x + 10, first.y + 10); await page.mouse.down();
    await page.mouse.move(secondRow.x + secondRow.width / 2, secondRow.y + secondRow.height / 2, { steps: 10 });
    await page.mouse.up();
    const dragged = await page.locator('.grid-card.selected').count();
    assert.ok(dragged >= 2, 'a marquee across two rows marks multiple cards');
    assert.equal(await page.locator('.marquee').count(), 0);
    await page.keyboard.press('Delete');
    await page.waitForFunction(n => Number(document.querySelector('#count-trash').textContent) === n, dragged);
    await page.keyboard.press('Control+z');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '0');
    await page.keyboard.press('Delete');
    await page.waitForFunction(n => Number(document.querySelector('#count-trash').textContent) === n, dragged);
    await page.locator('[data-filter="trash"]').click(); await page.keyboard.press('Control+a');
    await page.keyboard.press('Delete');
    assert.equal(await page.locator('#delete-prompt-text').textContent(), `Permanently delete ${dragged} photos?`);
    await page.keyboard.press('Escape'); await page.keyboard.press('r');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '0');
    await page.locator('[data-filter="pick"]').click();
    await page.waitForFunction(() => document.querySelectorAll('.grid-card').length === 1);
    await page.keyboard.press('e');
    await page.waitForFunction(() => document.querySelector('#review-image').dataset.complete === 'yes');
    await page.screenshot({ path: path.join(screenshots, 'photocull-review.png') });
    await page.locator('#settings-open').click();
    await page.locator('[data-settings-tab="metadata"]').click();
    await page.locator('#metadata-export summary').click();
    await page.locator('#export-xmp').click();
    await page.locator('#metadata-results:not([hidden])').waitFor();
    assert.match(await page.locator('#metadata-results').textContent(), /written/);
    assert.doesNotMatch(await page.locator('#metadata-results').textContent(), /Could not write/);
    await page.locator('#settings-dialog .close-dialog').click();
    await page.evaluate(folder => window.loadTestFolder(folder), photos);
    assert.equal(await page.locator('#count-pick').textContent(), '1');
    assert.equal(await page.locator('#count-reject').textContent(), '1');
    // Deleting rejects: browser mode has no Trash, so only permanent delete is offered.
    const total = Number(await page.locator('#count-all').textContent());
    await page.locator('[data-filter="reject"]').click();
    await page.locator('#delete-rejects:not([hidden])').waitFor();
    assert.match(await page.locator('#delete-rejects').textContent(), /Delete 1 reject$/);
    const rejected = await page.locator('#photo-name').textContent();
    await page.locator('#delete-rejects').click();
    assert.equal(await page.locator('#delete-mode-trash').isDisabled(), true);
    assert.equal(await page.locator('#delete-mode-permanent').isChecked(), true);
    await page.locator('#delete-confirm').click();
    await page.waitForFunction(() => document.querySelector('#count-reject').textContent === '0');
    assert.equal(await page.locator('#delete-dialog').isVisible(), false);
    assert.equal(Number(await page.locator('#count-all').textContent()), total - 1);
    await assert.rejects(fs.access(path.join(photos, rejected)), 'the rejected file is removed from disk');
    assert.equal(await page.locator('#delete-rejects').isVisible(), false);
    // Del moves a photo to PhotoCull's Trash without touching the disk; Ctrl+Z and R bring it back.
    const count = id => page.locator(`#count-${id}`).textContent();
    await page.locator('[data-filter="pick"]').click();
    const picked = await page.locator('#photo-name').textContent();
    await page.keyboard.press('Delete');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '1');
    assert.equal(await count('pick'), '0'); assert.equal(Number(await count('all')), total - 2);
    await fs.access(path.join(photos, picked));
    await page.keyboard.press('Control+z');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '0');
    assert.equal(await count('pick'), '1');
    await page.locator('[data-filter="pick"]').click(); await page.keyboard.press('Backspace');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '1');
    await page.locator('[data-filter="trash"]').click();
    assert.equal(await page.locator('#photo-name').textContent(), picked);
    await page.keyboard.press('r');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '0');
    assert.equal(await count('pick'), '1');
    // Shift+Del asks to delete permanently from any view; any other key cancels without acting.
    await page.locator('[data-filter="all"]').click();
    await page.keyboard.press('Shift+Delete');
    await page.locator('#delete-prompt:not([hidden])').waitFor();
    assert.match(await page.locator('#delete-prompt-text').textContent(), /^Permanently delete /);
    await page.keyboard.press('x');
    assert.equal(await page.locator('#delete-prompt').isVisible(), false);
    assert.equal(await count('reject'), '0', 'the cancelling key is not applied');
    // In the Trash view Del deletes for real (permanently in browser mode), after Enter.
    await page.locator('[data-filter="pick"]').click(); await page.keyboard.press('Delete');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '1');
    await page.locator('[data-filter="trash"]').click();
    await page.keyboard.press('Delete');
    await page.locator('#delete-prompt:not([hidden])').waitFor();
    assert.match(await page.locator('#delete-prompt-text').textContent(), new RegExp(`Permanently delete ${picked.replace('.', '\\.')}`));
    await page.screenshot({ path: path.join(screenshots, 'photocull-delete-prompt.png') });
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#count-trash').textContent === '0');
    await assert.rejects(fs.access(path.join(photos, picked)), 'the trashed file is removed from disk');
    assert.equal(Number(await count('all')), total - 2);
    await page.evaluate(folder => window.loadTestFolder(folder), photos);
    assert.equal(Number(await page.locator('#count-all').textContent()), total - 2, 'deleted photos stay gone after reopening');
    await page.locator('#search').fill('nothing-matches-this');
    assert.equal(await page.locator('#no-matches').isVisible(), true);
    await page.locator('#reset-filter').click();
    await page.locator('#shortcuts').click();
    assert.equal(await page.locator('#help-dialog').isVisible(), true);
    assert.deepEqual(errors, []);
    const stats = await page.evaluate(() => window.photocull.stats());
    const report = { passed: true, imageCount: Number(await page.locator('#count-all').textContent()), renderedGridCards: cardCount,
      checks: ['RAW preview display', 'keyboard picks and ratings', 'auto advance', 'undo/redo', 'reject', '100% zoom toggle', 'virtual grid', 'shift-click and batch undo', 'keyboard range, toggle and select all', 'marquee selection', 'batch trash, restore and delete prompt', 'pick filter', 'XMP export', 'reopen persistence', 'delete rejects', 'trash, restore and undo', 'permanent delete prompt', 'search empty state', 'shortcut help'], stats, errors };
    await fs.writeFile(path.join(screenshots, 'ui-smoke.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally {
    if (app) await app.close();
    await fs.rm(data, { recursive: true, force: true });
  }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
